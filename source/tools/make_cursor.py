#!/usr/bin/env python3
"""Builds src/cursor_art.hpp: the game's gauntlet cursor (hd/global/ui/cursor) as premultiplied BGRA
pixels for the overlay's cursor window.

Usage (from esr-wiki-plugin/overlay):
    python3 tools/make_cursor.py --cursor-dir "<D2R install>/data/data/hd/global/ui/cursor"

The cursor is the first frame of ohand.sprite (the pointing hand). The sprite is a strip of 16 frames (header:
width at byte 8, height at byte 12, RGBA pixels from byte 40). The frame is cropped to its visible pixels. The
hot spot (the point that clicks) is the fingertip: the middle of the topmost solid pixels.
"""
import argparse
import struct
from pathlib import Path

from PIL import Image

OVERLAY_DIR = Path(__file__).resolve().parent.parent
FRAMES_IN_STRIP = 16
LOGICAL_WIDTH = 125  # default size of the cursor on screen at 96 dpi in a 2160 px high window; shorter windows draw it smaller (the sprite frame is 138 wide)


def load_strip(path):
    data = Path(path).read_bytes()
    width, height = struct.unpack("<II", data[8:16])
    return Image.frombytes("RGBA", (width, height), data[40:40 + width * height * 4])


def frame_of(strip, index):
    cell = strip.width // FRAMES_IN_STRIP
    return strip.crop((index * cell, 0, (index + 1) * cell, strip.height))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cursor-dir", required=True)
    parser.add_argument("--width", type=int, default=LOGICAL_WIDTH,
                        help="cursor width on screen at 96 dpi (larger is bigger)")
    args = parser.parse_args()
    folder = Path(args.cursor_dir)
    strip = load_strip(folder / "ohand.sprite")
    frames = [frame_of(strip, 0)]  # the first frame, the pointing hand

    # One crop box for every frame: the union of their visible pixels.
    box = None
    for frame in frames:
        b = frame.getchannel("A").point(lambda v: 255 if v > 16 else 0).getbbox()
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    width = args.width
    height = round((box[3] - box[1]) * width / (box[2] - box[0]))
    words = []
    for frame in frames:
        pre = frame.crop(box).convert("RGBa").resize((width, height), Image.LANCZOS)
        raw = pre.tobytes()  # R, G, B, A with colour already multiplied by alpha
        words.append([(raw[i + 3] << 24) | (raw[i] << 16) | (raw[i + 1] << 8) | raw[i + 2]
                      for i in range(0, len(raw), 4)])  # 0xAARRGGBB, which is BGRA in memory
    idle = words[0]
    top = next(y for y in range(height) if any((idle[y * width + x] >> 24) > 160 for x in range(width)))
    xs = [x for x in range(width) if (idle[top * width + x] >> 24) > 160]
    hot_x, hot_y = round(sum(xs) / len(xs)), top

    lines = ["// Generated by tools/make_cursor.py from the game's ohand sprite. Do not edit.",
             "#pragma once", "#include <cstdint>", "",
             "constexpr int kCursorWidth = %d;     // image size; this is also the size on screen at 96 dpi" % width,
             "constexpr int kCursorHeight = %d;" % height,
             "constexpr int kCursorHotX = %d;      // hot spot (the fingertip)" % hot_x,
             "constexpr int kCursorHotY = %d;" % hot_y,
             "// Premultiplied alpha, top row first, 0xAARRGGBB.",
             "constexpr std::uint32_t kCursorPixels[kCursorWidth * kCursorHeight] = {"]
    for i in range(0, len(idle), 16):
        lines.append("    " + ",".join("0x%08X" % w for w in idle[i:i + 16]) + ",")
    lines.append("};")
    (OVERLAY_DIR / "src" / "cursor_art.hpp").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("cursor %dx%d, hot spot %d,%d" % (width, height, hot_x, hot_y))


if __name__ == "__main__":
    main()
